// Обнаружение сканеров в сети (план M1, R2, KTD-12). Здесь — то, что видит интерфейс: список
// найденных устройств. Адрес подключения по идентификатору знает только ядро.

/** Сканер, найденный по mDNS. Строки устройства — только текст для показа. */
export interface DiscoveredScanner {
  /** Непрозрачный идентификатор: интерфейс передаёт ядру его, а не адрес. */
  readonly id: string;
  /** Название из объявления; `null` — устройство себя не назвало. */
  readonly name: string | null;
  /** IPv4-адрес — виден пользователю: одно устройство на двух адресах даёт две записи. */
  readonly address: string;
  readonly port: number;
  /** Устройство без автоподачи показывается приглушённым и не выбирается. */
  readonly hasAdf: boolean;
}

export interface DiscoveryState {
  readonly scanners: readonly DiscoveredScanner[];
  /**
   * Почему поиск не идёт: `noNetwork` — нет ни одного внешнего IPv4-интерфейса, `socket` — ни на
   * одном интерфейсе не удалось открыть сокет. `null` — поиск идёт; пустой список тогда значит
   * «пока никто не ответил», а не сбой.
   */
  readonly failure: 'noNetwork' | 'socket' | null;
}
